import Foundation

/// Pack 1: shell scripts. Sources: the ShellCheck wiki (SC1017, SC1068,
/// SC1020/SC1035, SC2148, SC2164, SC2086). Every pattern matches only code:
/// the shell lexer (`CodeMask.scanShell`) blanks strings, comments and
/// here-documents first.
enum ShellRules {
    static let crlfID = "rules.sh.crlf"
    static let assignSpacesID = "rules.sh.assign-spaces"
    static let testBracketsID = "rules.sh.test-brackets"
    static let pastedID = "rules.sh.pasted-punctuation"
    static let shebangID = "rules.sh.shebang"
    static let cdID = "rules.sh.cd-unchecked"
    static let unquotedID = "rules.sh.unquoted-var"
    static let backticksID = "rules.sh.backticks"

    /// Autoconf and libtool output: generated, huge, full of multi-line
    /// strings and here-documents in other languages. Not the user's to fix.
    static let generated: Set<String> = ["configure", "config.status", "libtool", "ltmain.sh", "config.guess", "config.sub",
                                         "depcomp", "install-sh", "missing", "compile", "ltconfig", "mkinstalldirs"]

    /// Autoconf output under another name (config-host, a window of a
    /// configure script): its helper names give it away.
    static func looksGenerated(_ s: String) -> Bool {
        s.contains("as_fn_") || s.contains("ac_cv_") || s.contains("$as_echo") || s.contains("Generated by GNU Autoconf")
    }

    static let shell: @Sendable (String, String?) -> Bool = { l, name in
        l == "shell" && !generated.contains(name ?? "") && !(name ?? "").hasPrefix("configure.")
    }

    // MARK: Simple commands

    /// One simple command on a line: where its words start (after `if`,
    /// `then`, `!`, `sudo`…), where it ends, the keyword before it and the
    /// operator after it.
    struct Command {
        var start: Int          // the first word
        var end: Int            // exclusive, trailing spaces trimmed
        var lead: String        // the keyword skipped before it ("if", "while", "!", "" …)
        var after: String       // "&&", "||", "|", ";", "&", ")" or "" (end of line)
        var inSubstitution: Bool   // right after `$(` or a backtick
    }

    static let leadKeywords: Set<String> = ["if", "then", "else", "elif", "do", "while", "until", "!", "time", "{"]
    static let wrappers: Set<String> = ["sudo", "command", "exec", "nohup", "builtin"]

    /// The simple commands of the code (strings and comments blanked):
    /// split at `;`, `&&`, `||`, `|`, `&`, `(`, `)`, `{`, `}` and
    /// backticks; `[[ … ]]` and `(( … ))` are kept whole; a line ending in
    /// `\` continues the command on the next line, whose words are not
    /// treated as a new command.
    static func commands(_ code: NSString) -> [Command] {
        let n = code.length
        func ch(_ k: Int) -> unichar { k >= 0 && k < n ? code.character(at: k) : 0 }
        func isSpace(_ c: unichar) -> Bool { c == 32 || c == 9 || c == 13 }
        var out: [Command] = []
        var i = 0
        var segStart = 0, subst = false
        func finish(_ end: Int, after: String) {
            defer { segStart = end + after.utf16.count; subst = false }
            var a = segStart
            var lead = ""
            while true {
                while a < end, isSpace(ch(a)) || ch(a) == 10 { a += 1 }
                var w = a
                while w < end, !isSpace(ch(w)), ch(w) != 10 { w += 1 }
                let word = code.substring(with: NSRange(location: a, length: w - a))
                if leadKeywords.contains(word) { lead = word; a = w; continue }
                if wrappers.contains(word) {
                    // `sudo -u x rm …`: options of the wrapper aren't the command.
                    var b = w
                    while b < end, isSpace(ch(b)) { b += 1 }
                    if ch(b) == 45 { break }
                    a = w; continue
                }
                break
            }
            var e = end
            while e > a, isSpace(ch(e - 1)) || ch(e - 1) == 10 { e -= 1 }
            if e > a { out.append(Command(start: a, end: e, lead: lead, after: after, inSubstitution: subst)) }
        }
        while i < n {
            let c = ch(i)
            switch c {
            case 92:   // an escaped character; \ newline: the command goes on
                i += 2
            case 10:
                finish(i, after: "")
                i += 1
            case 38 where ch(i - 1) == 62 || ch(i + 1) == 62:   // >& &> redirections
                i += 1
            case 59, 38, 124:   // ; ;; & && | ||
                let two = ch(i + 1) == c ? 2 : 1
                let op = code.substring(with: NSRange(location: i, length: two))
                finish(i, after: op)
                i += two
            case 40 where ch(i + 1) == 40, 91 where ch(i + 1) == 91:   // (( … )) [[ … ]]
                let close: unichar = c == 40 ? 41 : 93
                var j = i + 2
                while j < n, !(ch(j) == close && ch(j + 1) == close), ch(j) != 10 { j += 1 }
                i = min(j + 2, n)
            case 40, 96:   // ( or a backtick: a command starts after it
                let sub = c == 96 || ch(i - 1) == 36
                finish(i, after: "(")
                subst = sub
                i += 1
            case 41:
                finish(i, after: ")")
                i += 1
            case 123, 125:
                // `{` and `}` only as words, not in ${x} or {a,b}.
                func blank(_ k: Int) -> Bool { k < 0 || k >= n || isSpace(ch(k)) || ch(k) == 10 || ch(k) == 59 }
                if blank(i - 1), blank(i + 1) { finish(i, after: c == 123 ? "{" : "}") }
                i += 1
            default:
                i += 1
            }
        }
        finish(n, after: "")
        return out
    }

    /// The words of a command (offsets in the text), split at spaces.
    static func words(_ code: NSString, _ cmd: Command) -> [NSRange] {
        var out: [NSRange] = []
        var i = cmd.start
        // (No array literal per character: a debug build allocates one each time.)
        func isSpace(_ c: unichar) -> Bool { c == 32 || c == 9 || c == 10 || c == 13 }
        while i < cmd.end {
            while i < cmd.end, isSpace(code.character(at: i)) { i += 1 }
            let a = i
            while i < cmd.end, !isSpace(code.character(at: i)) { i += 1 }
            if i > a { out.append(NSRange(location: a, length: i - a)) }
        }
        return out
    }

    static func isZsh(_ input: LintInput) -> Bool {
        let name = (input.fileName ?? "").lowercased()
        if name.hasSuffix(".zsh") || name.hasPrefix(".zsh") || name == ".zprofile" { return true }
        let first = input.string.prefix { $0 != "\n" }
        return first.hasPrefix("#!") && first.contains("zsh")
    }

    // MARK: SH1 CRLF

    static let crlf = LintRule(crlfID, applies: shell) { input in
        guard input.facts.lineEnding == .crlf, !input.facts.mixedLineEndings else { return nil }
        return LintFinding(kind: .warning, title: String(localized: "Windows line endings: this script won’t run."),
                           detail: String(localized: "The shell reads the CR at the end of each line as part of it (“bad interpreter: /bin/bash^M”). Use LF switches the file to Unix line endings (one undo)."))
    }

    // MARK: SH2 `NAME = value`

    static let notAssignments: Set<String> = ["echo", "printf", "print", "expr", "test", "set", "read", "local", "export", "declare",
                                              "typeset", "readonly", "alias", "let", "eval"]

    static let callParen = try! NSRegularExpression(pattern: #"(^|[^$])\("#)

    /// `$name` or `${name` in the text, not `$names`.
    static func isUsed(_ name: String, in s: NSString) -> Bool {
        for prefix in ["$", "${"] {
            var from = 0
            while from < s.length {
                let r = s.range(of: prefix + name, options: .literal, range: NSRange(location: from, length: s.length - from))
                guard r.location != NSNotFound else { break }
                let e = NSMaxRange(r)
                if e >= s.length { return true }
                guard let u = UnicodeScalar(s.character(at: e)), CharacterSet.alphanumerics.contains(u) || u == "_" else { return true }
                from = e
            }
        }
        return false
    }

    static let assignmentSpaces = LintRule(assignSpacesID, applies: shell) { input in
        let code = input.codeNS
        guard code.range(of: "=").location != NSNotFound else { return nil }
        var edits: [(NSRange, String)] = []
        var firstName = ""
        var used: [String: Bool] = [:]
        for (cmd, w) in zip(input.shellCommands, input.shellWords) where cmd.lead != "!" {
            guard w.count >= 2 else { continue }
            let name = code.substring(with: w[0])
            guard isName(name), !notAssignments.contains(name) else { continue }
            let second = code.substring(with: w[1])
            guard second.hasPrefix("="), !second.hasPrefix("==") else { continue }
            // A shell variable is meant to be used: `$NAME` or `${NAME` somewhere.
            // (Python or awk that a window shows as code never says $name.)
            // (`$NAME`, not `$NAMES`.) Checked first: it's memoised, the line below isn't.
            if used[name] == nil { used[name] = isUsed(name, in: input.text) }
            guard used[name] == true else { continue }
            // Another language's code (awk, Python, C) reaching here through
            // a window: `x = f(y);`. A shell value doesn't call or end in ;.
            let lineEnd = RulesHintProvider.lineRange(input.lines, containing: w[1].location).map(NSMaxRange) ?? cmd.end
            let rest = code.substring(with: NSRange(location: w[1].location, length: max(cmd.end, lineEnd) - w[1].location))
                .trimmingCharacters(in: .whitespaces)
            if rest.hasSuffix(";") || rest.hasSuffix("{") || callParen.firstMatch(in: rest, range: NSRange(location: 0, length: (rest as NSString).length)) != nil { continue }
            // A Python set or dict `NAME = {…}` isn't shell.
            guard !rest.dropFirst().trimmingCharacters(in: .whitespaces).hasPrefix("{"),
                  !rest.dropFirst().trimmingCharacters(in: .whitespaces).hasPrefix("[") else { continue }
            // From the end of the name to the start of the value: no spaces.
            var valueStart = NSMaxRange(w[1])
            if second == "=" {
                valueStart = w.count > 2 ? w[2].location : NSMaxRange(w[1])
                // `NAME = ` on its own line end: just drop the spaces.
                if w.count > 2, input.text.substring(with: NSRange(location: NSMaxRange(w[1]), length: w[2].location - NSMaxRange(w[1]))).contains("\n") { continue }
            } else {
                valueStart = w[1].location + 1
            }
            let r = NSRange(location: NSMaxRange(w[0]), length: valueStart - NSMaxRange(w[0]))
            edits.append((r, "="))
            if firstName.isEmpty { firstName = name }
        }
        guard let fix = RulesHintProvider.spanEdit(input.text, edits) else { return nil }
        return LintFinding(kind: .fix, title: String(localized: "“\(firstName) = …” runs a command. Remove the spaces?"),
                           detail: String(localized: "In the shell, an assignment has no spaces around “=”; with them, “\(firstName)” is run as a command.\(RulesHintProvider.andMore(edits.count))"),
                           range: fix.range, replacement: fix.replacement)
    }

    // MARK: SH3 `[`/`]` spacing

    static let testBrackets = LintRule(testBracketsID, applies: shell) { input in
        let code = input.codeNS
        guard code.range(of: "[").location != NSNotFound else { return nil }
        var edits: [(NSRange, String)] = []
        for cmd in input.shellCommands {
            let t = code.substring(with: NSRange(location: cmd.start, length: cmd.end - cmd.start)) as NSString
            let double = t.hasPrefix("[[")
            guard double || t.hasPrefix("[") else { continue }
            let open = double ? 2 : 1
            let close = double ? "]]" : "]"
            guard t.hasSuffix(close), t.length > open + close.utf16.count else { continue }
            let inner = t.substring(with: NSRange(location: open, length: t.length - open - close.utf16.count))
            // A test has words inside; `[yY])` in a case is a pattern. A
            // `=~` regex may hold brackets of its own.
            guard inner.contains(" ") || inner.contains("\t"), !inner.contains("=~") else { continue }
            // `[[` and `]]` are scanned whole by `commands`: a single `[`
            // must not be the first half of one.
            if !double, t.hasSuffix("]]") { continue }
            let afterOpen = t.character(at: open)
            let beforeClose = t.character(at: t.length - close.utf16.count - 1)
            if afterOpen != 32, afterOpen != 9 { edits.append((NSRange(location: cmd.start + open, length: 0), " ")) }
            if beforeClose != 32, beforeClose != 9 { edits.append((NSRange(location: cmd.end - close.utf16.count, length: 0), " ")) }
        }
        guard let fix = RulesHintProvider.spanEdit(input.text, edits) else { return nil }
        return LintFinding(kind: .fix, title: String(localized: "“[” and “]” need spaces inside. Add them?"),
                           detail: String(localized: "“[” is a command and “]” its last word: “[$a = b ]” runs a command named “[$a”, and “\"b\"]” is never seen as the closing bracket.\(RulesHintProvider.andMore(edits.count))"),
                           range: fix.range, replacement: fix.replacement)
    }

    // MARK: SH4 Pasted curly quotes and dashes

    static let typographic = CharacterSet(charactersIn: "\u{201C}\u{201D}\u{2018}\u{2019}\u{2013}\u{2014}")

    static let pastedPunctuation = LintRule(pastedID, applies: shell) { input in
        let s = input.text
        // Cheap test first: no typographic quote or dash at all.
        guard s.rangeOfCharacter(from: typographic).location != NSNotFound else { return nil }
        func isLetter(_ k: Int) -> Bool {
            guard k >= 0, k < s.length, let u = UnicodeScalar(s.character(at: k)) else { return false }
            return CharacterSet.letters.contains(u)
        }
        func isBlank(_ k: Int) -> Bool { k < 0 || k >= s.length || [32, 9, 10, 13].contains(s.character(at: k)) }
        var edits: [(NSRange, String)] = []
        for k in 0..<s.length {
            let c = s.character(at: k)
            switch c {
            case 0x201C, 0x2018:   // “ ‘ opening: quoting
                guard input.isCode(k) else { continue }
                edits.append((NSRange(location: k, length: 1), c == 0x201C ? "\"" : "'"))
            case 0x201D, 0x2019:   // ” ’ closing; not an apostrophe inside a word (don’t)
                guard input.isCode(k), !(isLetter(k - 1) && isLetter(k + 1)) else { continue }
                edits.append((NSRange(location: k, length: 1), c == 0x201D ? "\"" : "'"))
            case 0x2013, 0x2014:   // – — before an option: a pasted -x or --flag
                guard input.isCode(k), isBlank(k - 1), isLetter(k + 1) else { continue }
                edits.append((NSRange(location: k, length: 1), c == 0x2014 ? "--" : "-"))
            default: continue
            }
        }
        guard let fix = RulesHintProvider.spanEdit(s, edits) else { return nil }
        return LintFinding(kind: .fix, title: String(localized: "Curly quotes or long dashes in a command. Straighten them?"),
                           detail: String(localized: "\(edits.count) typographic marks, probably pasted from a web page or a chat: the shell sees “ and – as ordinary letters, not quotes and options."),
                           range: fix.range, replacement: fix.replacement)
    }

    // MARK: SH5 Missing shebang

    static let shebangExtensions: Set<String> = ["sh", "bash", "zsh", "ksh"]
    static let bashisms = try! NSRegularExpression(pattern: #"\[\[|^\s*function\s|\w=\(|\$\{\w+\[|<<<|\bsource\s|\bdeclare\s|\(\(|\$'"#, options: [.anchorsMatchLines])

    /// Every match of `bashisms` contains one of these: without any, the
    /// regex (eight alternatives tried at every offset) needn't run.
    static let bashismLiterals = ["[[", "function", "=(", "${", "<<<", "source", "declare", "((", "$'"]

    static func hasBashism(_ code: NSString) -> Bool {
        guard bashismLiterals.contains(where: { code.range(of: $0, options: .literal).location != NSNotFound }) else { return false }
        return bashisms.firstMatch(in: code as String, range: NSRange(location: 0, length: code.length)) != nil
    }

    static let functionHeader = try! NSRegularExpression(pattern: #"^\s*(function\s+[\w:-]+|[\w:-]+\s*\(\s*\))"#)
    static let settingOrFunction = try! NSRegularExpression(pattern: #"^((export|readonly)\s+)?[A-Za-z_]\w*(\+?=|$)|^[)}{'"]|^[\w:-]+\s*\(\s*\)|^function\s"#)

    /// A shell variable name: [A-Za-z_][A-Za-z0-9_]*.
    static func isName(_ s: String) -> Bool {
        guard let f = s.utf8.first, f == 95 || (65...90).contains(f) || (97...122).contains(f) else { return false }
        return s.utf8.allSatisfy { $0 == 95 || (48...57).contains($0) || (65...90).contains($0) || (97...122).contains($0) }
    }

    static let programSignals = try! NSRegularExpression(pattern: #"\$[1-9@*#]|\$\{[1-9@*#]|\b(exit|getopts|shift)\b|^set -|^(echo|printf|cd|mkdir|rm|cp|mv|read)\b"#, options: [.anchorsMatchLines])

    static let missingShebang = LintRule(shebangID, wholeDocument: true, applies: { l, name in
        shell(l, name) && shebangExtensions.contains(RulesHintProvider.ext(name))
    }) { input in
        guard input.facts.unsavedSince == nil, input.fileName != nil else { return nil }
        let t = input.string
        guard t.contains(where: { !$0.isWhitespace }), !t.hasPrefix("#!"), !t.hasPrefix("\u{FEFF}#!"),
              // A project that runs ShellCheck on it has set the shell there (.shellcheckrc).
              !t.contains("# shellcheck ") else { return nil }
        // A file meant to be sourced says so near the top, or starts with
        // a function definition (a library): it needs no shebang.
        let head = t.prefix(600).lowercased()
        if head.contains("source") || head.contains("sourced") || head.contains("# . ") { return nil }
        if let firstCode = t.split(separator: "\n").first(where: { let l = $0.trimmingCharacters(in: .whitespaces); return !l.isEmpty && !l.hasPrefix("#") }),
           functionHeader.firstMatch(in: String(firstCode), range: NSRange(location: 0, length: (String(firstCode) as NSString).length)) != nil { return nil }
        // Only settings at the top level (NAME=value, export …): a fragment
        // another script sources.
        let topLevel = input.code.split(separator: "\n").filter { l in
            guard let f = l.first else { return false }
            return f != " " && f != "\t"
        }.map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
        if topLevel.allSatisfy({ settingOrFunction.firstMatch(in: $0, range: NSRange(location: 0, length: ($0 as NSString).length)) != nil }) { return nil }
        // And something only a script run on its own does: read its
        // arguments, exit, or run commands at the top level. A fragment
        // that sets variables for the script sourcing it doesn't.
        guard programSignals.firstMatch(in: input.code, range: NSRange(location: 0, length: input.codeNS.length)) != nil else { return nil }
        let e = RulesHintProvider.ext(input.fileName)
        let line: String
        switch e {
        case "zsh": line = "#!/bin/zsh"
        case "ksh": line = "#!/bin/ksh"
        case "bash": line = "#!/bin/bash"
        default:
            line = hasBashism(input.codeNS) ? "#!/bin/bash" : "#!/bin/sh"
        }
        return LintFinding(kind: .fix, title: String(localized: "No #! line. Add “\(line)”?"),
                           detail: String(localized: "Without one, the script runs in whatever shell starts it, and “./script” may not run it at all."),
                           range: NSRange(location: 0, length: 0), replacement: line + "\n")
    }

    // MARK: SH6 `cd` without `|| exit`, then rm/mv/cp

    static let errexit = try! NSRegularExpression(pattern: #"(?m)^[ \t]*set[ \t]+(-[a-zA-Z]*e|-o[ \t]+errexit|-e)|^#!.*[ \t]-[a-zA-Z]*e\b"#)
    static let destructive: Set<String> = ["rm", "mv", "cp"]

    /// Whether an argument names something relative to the current folder.
    static func isRelative(_ word: String) -> Bool {
        guard let f = word.first, f != "-" else { return false }
        return !["/", "~", "$", "\"", "'"].contains(f)
    }

    static let cdUnchecked = LintRule(cdID, wholeDocument: true, applies: shell) { input in
        let code = input.codeNS
        guard code.range(of: "cd ").location != NSNotFound,
              // (The NSString, not the Swift string: no bridging; first match only.)
              errexit.firstMatch(in: input.text as String, range: NSRange(location: 0, length: input.text.length)) == nil else { return nil }
        var lastCD: Command?
        var flagged: [Int: Command] = [:]
        var firstTarget = ""
        for (cmd, w) in zip(input.shellCommands, input.shellWords) {
            guard let first = w.first else { continue }
            let name = code.substring(with: first)
            if name == "cd" || name == "pushd" {
                let checked = cmd.after == "||" || cmd.after == "&&" || ["if", "while", "until", "!", "elif"].contains(cmd.lead) || cmd.inSubstitution
                let args = w.dropFirst().map { code.substring(with: $0) }.filter { !$0.hasPrefix("-") }
                // `cd` alone goes home: it doesn't fail.
                lastCD = checked || args.isEmpty ? nil : cmd
                continue
            }
            guard destructive.contains(name), let cd = lastCD else { continue }
            let args = w.dropFirst().map { input.text.substring(with: $0) }
            guard args.contains(where: isRelative) else { continue }
            if flagged[cd.start] == nil {
                flagged[cd.start] = cd
                if firstTarget.isEmpty { firstTarget = name }
            }
        }
        let edits = flagged.values.map { (NSRange(location: $0.end, length: 0), " || exit 1") }
        guard let fix = RulesHintProvider.spanEdit(input.text, edits), let first = flagged.values.map(\.start).min() else { return nil }
        return LintFinding(kind: .warning, title: String(localized: "If this cd fails, \(firstTarget) runs in the wrong folder."),
                           detail: String(localized: "A “cd” \(input.at(first)) has no “|| exit”: if the folder is missing, the script carries on where it was and the “\(firstTarget)” after it works on the wrong files. Fix it adds “|| exit 1”.\(RulesHintProvider.andMore(edits.count))"),
                           range: fix.range, replacement: fix.replacement)
    }

    // MARK: SH7 Unquoted `$var` in rm/mv/cp

    static let unquotedVariable = LintRule(unquotedID, applies: shell) { input in
        guard !isZsh(input) else { return nil }   // zsh doesn't split unquoted variables
        let code = input.codeNS
        guard code.range(of: "$").location != NSNotFound else { return nil }
        var edits: [(NSRange, String)] = []
        var example = ""
        for w in input.shellWords {
            guard let first = w.first, destructive.contains(code.substring(with: first)) else { continue }
            for word in w.dropFirst() {
                let vars = variables(code, in: word)
                guard !vars.isEmpty else { continue }
                let original = input.text.substring(with: word)
                if example.isEmpty { example = input.text.substring(with: vars[0]) }
                // The whole word in quotes when nothing in it needs to stay
                // unquoted (a glob, a quote, a backslash); else each variable.
                if original.rangeOfCharacter(from: mustStayUnquoted) == nil || vars.count == 1 && vars[0] == word {
                    edits.append((word, "\"" + original + "\""))
                } else if !original.contains("`") {
                    for v in vars { edits.append((v, "\"" + input.text.substring(with: v) + "\"")) }
                }
            }
        }
        guard let fix = RulesHintProvider.spanEdit(input.text, edits) else { return nil }
        return LintFinding(kind: .fix, title: String(localized: "Unquoted “\(String(example.prefix(20)))” in rm, mv or cp. Quote it?"),
                           detail: String(localized: "Without quotes, a value with spaces or * becomes several paths, or none: “rm -rf $DIR/out” with an empty DIR is “rm -rf /out”. Quoting keeps it one path.\(RulesHintProvider.andMore(edits.count))"),
                           range: fix.range, replacement: fix.replacement)
    }

    static let mustStayUnquoted = CharacterSet(charactersIn: "*?[]\"'\\`{}~")

    /// The unquoted variable expansions in a word of code (`$x`, `${x…}`,
    /// `$1`, `$@`, `$*`); not `$#`, `$?`, `$$`, `$!`, `${#x}` (numbers) or
    /// `$(…)`.
    static func variables(_ code: NSString, in word: NSRange) -> [NSRange] {
        var out: [NSRange] = []
        var i = word.location
        let end = NSMaxRange(word)
        func ch(_ k: Int) -> unichar { k < end ? code.character(at: k) : 0 }
        while i < end {
            guard ch(i) == 36 else { i += ch(i) == 92 ? 2 : 1; continue }
            let n = ch(i + 1)
            if n == 123 {   // ${
                if ch(i + 2) == 35 { i += 2; continue }   // ${#x}
                var j = i + 2, depth = 1
                while j < end, depth > 0 { if ch(j) == 123 { depth += 1 } else if ch(j) == 125 { depth -= 1 }; j += 1 }
                if depth == 0 { out.append(NSRange(location: i, length: j - i)) }
                i = j
            } else if let u = UnicodeScalar(n), CharacterSet.letters.contains(u) || u == "_" {
                var j = i + 2
                while j < end, let v = UnicodeScalar(ch(j)), CharacterSet.alphanumerics.contains(v) && v.isASCII || v == "_" { j += 1 }
                out.append(NSRange(location: i, length: j - i))
                i = j
            } else if (48...57).contains(n) || n == 64 || n == 42 {   // $1 $@ $*
                out.append(NSRange(location: i, length: 2))
                i += 2
            } else {
                i += 2
            }
        }
        return out
    }

    // MARK: Style: backticks (SC2006)

    static let backtickSub = try! NSRegularExpression(pattern: #"`([^`\\\n]*)`"#)

    static let backticks = LintRule(backticksID, tier: .style, applies: shell) { input in
        guard input.text.range(of: "`").location != NSNotFound, let mask = input.mask else { return nil }
        // In code, or inside a "…" string, where `…` is still a command.
        var edits: [(NSRange, String)] = []
        for m in RulesHintProvider.matches(backtickSub, input.string) {
            let r = m.range
            if let sp = mask.span(at: r.location) {
                guard sp.kind == .string, input.text.character(at: sp.range.location) == 34, NSMaxRange(r) < NSMaxRange(sp.range) else { continue }
                // A "…" string over several lines: in a window the quoting may be
                // out of step (the window started inside a string), so only one-line strings.
                if input.text.range(of: "\n", options: [], range: sp.range).location != NSNotFound { continue }
            }
            let inner = input.text.substring(with: m.range(at: 1))
            guard !inner.trimmingCharacters(in: .whitespaces).isEmpty else { continue }
            edits.append((r, "$(" + inner + ")"))
        }
        guard let fix = RulesHintProvider.spanEdit(input.text, edits) else { return nil }
        return LintFinding(kind: .fix, title: String(localized: "Backticks are the old form. Use $(…)?"),
                           detail: String(localized: "$(…) nests without escaping and is easier to read; it does the same thing.\(RulesHintProvider.andMore(edits.count))"),
                           range: fix.range, replacement: fix.replacement)
    }
}

extension RulesHintProvider {
    /// The line ending a hint's button switches the document to (the shell
    /// CRLF warning: LF), or nil.
    public static func lineEndingFix(_ hint: OwlHint) -> LineEnding? {
        hint.id == ShellRules.crlfID ? .lf : nil
    }
}

extension LintInput {
    /// The shell's simple commands, split once per query.
